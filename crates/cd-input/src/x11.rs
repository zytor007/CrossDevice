use crate::error::InputError;

/// XIAllDevices; root selections need every slave stream here because XTest
/// events are routed through the virtual XTEST slave before the master.
const ALL_DEVICES: u16 = 0;

/// FP1616 values are 16-bit integers with 16 fractional bits.
fn fp1616_to_px(value: i32) -> f64 {
    f64::from(value) / 65536.0
}

#[derive(Debug, Clone, PartialEq)]
pub enum CapturedEvent {
    Motion {
        x: f64,
        y: f64,
        source_id: u16,
        time_ms: u32,
    },
    Button {
        button: u8,
        pressed: bool,
        source_id: u16,
        time_ms: u32,
    },
    Key {
        keycode: u8,
        pressed: bool,
        source_id: u16,
        time_ms: u32,
    },
}

impl CapturedEvent {
    pub fn source_id(&self) -> u16 {
        match self {
            Self::Motion { source_id, .. }
            | Self::Button { source_id, .. }
            | Self::Key { source_id, .. } => *source_id,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SelfTestReport {
    pub original: (i16, i16),
    pub target: (i16, i16),
    pub delta: (i16, i16),
    pub motion_events: usize,
    pub button_events: usize,
    pub key_events: usize,
    pub restored: bool,
    pub first_motion: Option<(i16, i16)>,
}

impl SelfTestReport {
    pub fn passed(&self) -> bool {
        self.motion_events > 0 && self.restored
    }
}

pub struct X11Capture {
    conn: RustConnection,
    root: u32,
    ignored_sources: Vec<u16>,
}

impl X11Capture {
    /// Product capture: ignores events generated by XTest (our own injection),
    /// which prevents a feedback loop between peers.
    pub fn open() -> Result<Self, InputError> {
        Self::open_impl(true)
    }

    /// Diagnostic capture: includes injected events, used by probe/self-test.
    pub fn open_including_injected() -> Result<Self, InputError> {
        Self::open_impl(false)
    }

    fn open_impl(ignore_injected: bool) -> Result<Self, InputError> {
        let (conn, screen_num) = x11rb::connect(None).map_err(|error| match error {
            x11rb::errors::ConnectError::DisplayParsingError(_) => InputError::NoDisplay,
            other => InputError::Connect(other.to_string()),
        })?;
        let root = conn.setup().roots[screen_num].root;

        let version = conn
            .xinput_xi_query_version(2, 2)
            .map_err(|error| InputError::XInput(error.to_string()))?
            .reply()
            .map_err(|error| InputError::XInput(error.to_string()))?;
        if version.major_version < 2 {
            return Err(InputError::XInput(format!(
                "server reports XInput {}",
                version.major_version
            )));
        }

        let ignored_sources = if ignore_injected {
            let devices = conn
                .xinput_xi_query_device(0_u16)
                .map_err(|error| InputError::XInput(error.to_string()))?
                .reply()
                .map_err(|error| InputError::XInput(error.to_string()))?;
            devices
                .infos
                .iter()
                .filter(|info| {
                    String::from_utf8_lossy(&info.name)
                        .to_ascii_uppercase()
                        .contains("XTEST")
                })
                .map(|info| info.deviceid)
                .collect()
        } else {
            Vec::new()
        };

        let mask = xinput::XIEventMask::MOTION
            | xinput::XIEventMask::BUTTON_PRESS
            | xinput::XIEventMask::BUTTON_RELEASE
            | xinput::XIEventMask::KEY_PRESS
            | xinput::XIEventMask::KEY_RELEASE;
        let masks = [xinput::EventMask {
            deviceid: ALL_DEVICES,
            mask: vec![mask],
        }];
        conn.xinput_xi_select_events(root, &masks)?.check()?;
        conn.flush()?;

        Ok(Self {
            conn,
            root,
            ignored_sources,
        })
    }

    pub fn root(&self) -> u32 {
        self.root
    }

    pub fn ignored_sources(&self) -> &[u16] {
        &self.ignored_sources
    }

    /// Non-blocking drain of every event that is already queued.
    pub fn drain(&self) -> Result<Vec<CapturedEvent>, InputError> {
        let mut events = Vec::new();
        while let Some(event) = self.conn.poll_for_event()? {
            if let Some(event) = decode(event) {
                if !self.ignored_sources.contains(&event.source_id()) {
                    events.push(event);
                }
            }
        }
        Ok(events)
    }

    /// Poll for a fixed duration. Intended for probes and the self-test; the
    /// real daemon will block on the X connection in its own thread.
    pub fn probe(&self, duration: Duration) -> Result<Vec<CapturedEvent>, InputError> {
        let deadline = Instant::now() + duration;
        let mut events = Vec::new();
        loop {
            events.extend(self.drain()?);
            if Instant::now() >= deadline {
                break;
            }
            thread::sleep(Duration::from_millis(4));
        }
        Ok(events)
    }
}

fn decode(event: Event) -> Option<CapturedEvent> {
    match event {
        Event::XinputMotion(event) => Some(CapturedEvent::Motion {
            x: fp1616_to_px(event.root_x),
            y: fp1616_to_px(event.root_y),
            source_id: event.sourceid,
            time_ms: event.time,
        }),
        Event::XinputButtonPress(event) => Some(CapturedEvent::Button {
            button: detail_to_u8(event.detail),
            pressed: true,
            source_id: event.sourceid,
            time_ms: event.time,
        }),
        Event::XinputButtonRelease(event) => Some(CapturedEvent::Button {
            button: detail_to_u8(event.detail),
            pressed: false,
            source_id: event.sourceid,
            time_ms: event.time,
        }),
        Event::XinputKeyPress(event) => Some(CapturedEvent::Key {
            keycode: detail_to_u8(event.detail),
            pressed: true,
            source_id: event.sourceid,
            time_ms: event.time,
        }),
        Event::XinputKeyRelease(event) => Some(CapturedEvent::Key {
            keycode: detail_to_u8(event.detail),
            pressed: false,
            source_id: event.sourceid,
            time_ms: event.time,
        }),
        _ => None,
    }
}

fn detail_to_u8(value: u32) -> u8 {
    u8::try_from(value).unwrap_or(u8::MAX)
}

pub struct X11Injector {
    conn: RustConnection,
    root: u32,
    width: u16,
    height: u16,
}

impl X11Injector {
    pub fn open() -> Result<Self, InputError> {
        let (conn, screen_num) = x11rb::connect(None).map_err(|error| match error {
            x11rb::errors::ConnectError::DisplayParsingError(_) => InputError::NoDisplay,
            other => InputError::Connect(other.to_string()),
        })?;
        let root = conn.setup().roots[screen_num].root;
        let width = conn.setup().roots[screen_num].width_in_pixels;
        let height = conn.setup().roots[screen_num].height_in_pixels;

        conn.xtest_get_version(2, 2)
            .map_err(|error| InputError::XTest(error.to_string()))?
            .reply()
            .map_err(|error| InputError::XTest(error.to_string()))?;

        Ok(Self {
            conn,
            root,
            width,
            height,
        })
    }

    pub fn pointer(&self) -> Result<(i16, i16), InputError> {
        let reply = self.conn.query_pointer(self.root)?.reply()?;
        Ok((reply.root_x, reply.root_y))
    }

    pub fn move_pointer(&self, x: i16, y: i16) -> Result<(), InputError> {
        self.conn
            .xtest_fake_input(xproto::MOTION_NOTIFY_EVENT, 0, 0, self.root, x, y, 0)?
            .check()?;
        self.conn.flush()?;
        Ok(())
    }

    pub fn move_relative(&self, dx: i16, dy: i16) -> Result<(), InputError> {
        let (x, y) = self.pointer()?;
        let target_x = clamp_axis(i32::from(x) + i32::from(dx), self.width);
        let target_y = clamp_axis(i32::from(y) + i32::from(dy), self.height);
        self.move_pointer(target_x, target_y)
    }

    pub fn button(&self, button: u8, pressed: bool) -> Result<(), InputError> {
        let kind = if pressed {
            xproto::BUTTON_PRESS_EVENT
        } else {
            xproto::BUTTON_RELEASE_EVENT
        };
        self.conn
            .xtest_fake_input(kind, button, 0, self.root, 0, 0, 0)?
            .check()?;
        self.conn.flush()?;
        Ok(())
    }

    pub fn key(&self, keycode: u8, pressed: bool) -> Result<(), InputError> {
        let kind = if pressed {
            xproto::KEY_PRESS_EVENT
        } else {
            xproto::KEY_RELEASE_EVENT
        };
        self.conn
            .xtest_fake_input(kind, keycode, 0, self.root, 0, 0, 0)?
            .check()?;
        self.conn.flush()?;
        Ok(())
    }
}

fn clamp_axis(value: i32, extent: u16) -> i16 {
    let max = i32::from(extent.saturating_sub(1));
    i16::try_from(value.clamp(0, max)).unwrap_or(0)
}

/// Tracks the focused X11 window so clipboard publishing can skip sensitive
/// applications (password managers) listed in the policy.
pub struct ActiveWindow {
    conn: RustConnection,
    root: u32,
    active_atom: u32,
}

impl ActiveWindow {
    pub fn open() -> Result<Self, InputError> {
        let (conn, screen_num) = x11rb::connect(None).map_err(|error| match error {
            x11rb::errors::ConnectError::DisplayParsingError(_) => InputError::NoDisplay,
            other => InputError::Connect(other.to_string()),
        })?;
        let root = conn.setup().roots[screen_num].root;
        let active_atom = conn
            .intern_atom(false, b"_NET_ACTIVE_WINDOW")
            .map_err(|error| InputError::Request(error.to_string()))?
            .reply()
            .map_err(|error| InputError::Request(error.to_string()))?
            .atom;
        Ok(Self {
            conn,
            root,
            active_atom,
        })
    }

    /// WM_CLASS of the focused window, e.g. `"firefox"` or `"1password"`.
    pub fn class_name(&self) -> Option<String> {
        let window = self.active_window()?;
        let reply = self
            .conn
            .get_property(
                false,
                window,
                xproto::AtomEnum::WM_CLASS,
                xproto::AtomEnum::STRING,
                0,
                1024,
            )
            .ok()?
            .reply()
            .ok()?;
        let parts = reply
            .value
            .split(|byte| *byte == 0)
            .filter(|part| !part.is_empty())
            .collect::<Vec<_>>();
        let name = match parts.as_slice() {
            // WM_CLASS is (instance, class); the class is the app family name.
            [_, class, ..] => *class,
            [instance] => *instance,
            [] => return None,
        };
        Some(String::from_utf8_lossy(name).to_string())
    }

    fn active_window(&self) -> Option<u32> {
        let reply = self
            .conn
            .get_property(
                false,
                self.root,
                self.active_atom,
                xproto::AtomEnum::WINDOW,
                0,
                1,
            )
            .ok()?
            .reply()
            .ok()?;
        let window = reply.value32()?.next()?;
        if window != 0 {
            return Some(window);
        }
        // WMs without EWMH still expose the focus window via GetInputFocus.
        let focus = self.conn.get_input_focus().ok()?.reply().ok()?;
        // 0 = None, 1 = PointerRoot; neither carries a WM_CLASS.
        if focus.focus == 0 || focus.focus == 1 {
            return None;
        }
        Some(focus.focus)
    }
}

/// Moves the pointer a few pixels and back while capturing, proving that the
/// XI2 capture path and XTest injection path both work on this display.
pub fn self_test() -> Result<SelfTestReport, InputError> {
    let injector = X11Injector::open()?;
    let original = injector.pointer()?;
    let dx = if i32::from(original.0) + 8 < i32::from(injector.width) {
        8_i16
    } else {
        -8_i16
    };
    let dy = if i32::from(original.1) + 8 < i32::from(injector.height) {
        8_i16
    } else {
        -8_i16
    };
    let target = (
        i16::try_from(i32::from(original.0) + i32::from(dx)).unwrap_or(original.0),
        i16::try_from(i32::from(original.1) + i32::from(dy)).unwrap_or(original.1),
    );

    let capture = X11Capture::open_including_injected()?;
    thread::sleep(Duration::from_millis(80));
    injector.move_pointer(target.0, target.1)?;
    thread::sleep(Duration::from_millis(120));
    let outbound = capture.drain()?;

    injector.move_pointer(original.0, original.1)?;
    thread::sleep(Duration::from_millis(120));
    let inbound = capture.drain()?;

    let restored = injector.pointer()? == original;
    let mut motion_events = 0;
    let mut button_events = 0;
    let mut key_events = 0;
    let mut first_motion = None;
    for event in outbound.into_iter().chain(inbound) {
        match event {
            CapturedEvent::Motion { x, y, .. } => {
                motion_events += 1;
                if first_motion.is_none() {
                    first_motion = Some((x.round() as i16, y.round() as i16));
                }
            }
            CapturedEvent::Button { .. } => button_events += 1,
            CapturedEvent::Key { .. } => key_events += 1,
        }
    }

    Ok(SelfTestReport {
        original,
        target,
        delta: (dx, dy),
        motion_events,
        button_events,
        key_events,
        restored,
        first_motion,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixed_point_conversion() {
        assert!((fp1616_to_px(65_536) - 1.0).abs() < 1e-9);
        assert!((fp1616_to_px(32_768) - 0.5).abs() < 1e-9);
        assert!((fp1616_to_px(-65_536) + 1.0).abs() < 1e-9);
    }

    #[test]
    fn relative_moves_stay_on_screen() {
        assert_eq!(clamp_axis(-10, 1920), 0);
        assert_eq!(clamp_axis(5000, 1920), 1919);
        assert_eq!(clamp_axis(100, 1920), 100);
    }

    #[test]
    fn detail_is_truncated_safely() {
        assert_eq!(detail_to_u8(1), 1);
        assert_eq!(detail_to_u8(300), 255);
    }
}
