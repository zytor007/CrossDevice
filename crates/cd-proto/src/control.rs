/// Capability bits advertised in `hello`; peers intersect them.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(transparent)]
pub struct Capabilities(pub u32);

impl Capabilities {
    pub const INPUT: Self = Self(1 << 0);
    pub const CLIPBOARD_TEXT: Self = Self(1 << 1);
    pub const CLIPBOARD_HTML: Self = Self(1 << 2);
    pub const CLIPBOARD_IMAGE: Self = Self(1 << 3);
    pub const CLIPBOARD_FILES: Self = Self(1 << 4);
    pub const FILE_TRANSFER: Self = Self(1 << 5);
    pub const DIRECTORY_TRANSFER: Self = Self(1 << 6);
    pub const RESUME_TRANSFER: Self = Self(1 << 7);
    pub const SAS_PAIRING: Self = Self(1 << 8);

    pub const fn empty() -> Self {
        Self(0)
    }

    pub const fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }

    pub const fn union(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }

    pub const fn is_empty(self) -> bool {
        self.0 == 0
    }
}

impl std::ops::BitOr for Capabilities {
    type Output = Self;

    fn bitor(self, rhs: Self) -> Self::Output {
        self.union(rhs)
    }
}

impl std::ops::BitOrAssign for Capabilities {
    fn bitor_assign(&mut self, rhs: Self) {
        self.0 |= rhs.0;
    }
}

/// Modifier state at handoff time; prevents "stuck Ctrl" across machines.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(transparent)]
pub struct Modifiers(pub u8);

impl Modifiers {
    pub const CTRL: Self = Self(1 << 0);
    pub const SHIFT: Self = Self(1 << 1);
    pub const ALT: Self = Self(1 << 2);
    pub const META: Self = Self(1 << 3);

    pub const fn empty() -> Self {
        Self(0)
    }

    pub const fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }

    pub const fn is_empty(self) -> bool {
        self.0 == 0
    }
}

