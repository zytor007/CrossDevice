/// C0 control channel message.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ControlMessage {
    Hello(Hello),
    PairBegin(PairBegin),
    PairConfirm(PairConfirm),
    LayoutSet(LayoutSet),
    InputOwner(InputOwner),
    ClipboardAnnounce(ClipboardAnnounce),
    TransferOffer(TransferOffer),
    FileSendRequest(FileSendRequest),
    FileSendGrant(FileSendGrant),
    FileSendRelease(FileSendRelease),
    TransferCancel(TransferCancel),
    TransferPause(TransferPause),
    PairSettings(PairSettings),
    FeatureSet(FeatureSet),
    Heartbeat(Heartbeat),
    Error(ProtocolError),
}

impl ControlMessage {
    pub fn to_json(&self) -> Result<String, serde_json::Error> {
        serde_json::to_string(self)
    }

    pub fn from_json(input: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(input)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use cd_geometry::presets;

    fn sample_hello() -> Hello {
        Hello {
            protocol: ProtocolVersion::CURRENT,
            device_id: "linux-4k".to_owned(),
            device_name: "Studio Desktop".to_owned(),
            platform: "linux-x11".to_owned(),
            capabilities: Capabilities::INPUT
                | Capabilities::CLIPBOARD_TEXT
                | Capabilities::FILE_TRANSFER,
            monitors: vec![presets::linux_4k()],
        }
    }

    fn sample_messages() -> Vec<ControlMessage> {
        let layout = presets::compose_air(presets::macbook_air_13(), 0.0);
        let pairs = layout.pair_edges();
        vec![
            ControlMessage::Hello(sample_hello()),
            ControlMessage::PairBegin(PairBegin {
                nonce: "00112233445566778899aabbccddeeff".to_owned(),
                cert_fingerprint: "ab".repeat(32),
            }),
            ControlMessage::PairConfirm(PairConfirm {
                code: "042817".to_owned(),
                confirm: true,
            }),
            ControlMessage::LayoutSet(LayoutSet {
                revision: 3,
                screens: layout.screens,
                edge_pairs: pairs,
            }),
            ControlMessage::InputOwner(InputOwner {
                owner: "macbook-air-13".to_owned(),
                phase: OwnerPhase::HandoffOut,
                modifiers: Modifiers::CTRL,
            }),
            ControlMessage::ClipboardAnnounce(ClipboardAnnounce {
                kind: ClipboardKind::Text,
                hash: "cd".repeat(32),
                size: 42,
                origin_id: "linux-4k".to_owned(),
                seq: 7,
            }),
            ControlMessage::TransferOffer(TransferOffer {
                task_id: "task-1".to_owned(),
                root_name: "design-assets".to_owned(),
                total_bytes: 8_000_000_000,
                file_count: 1200,
                directory_count: 84,
            }),
            ControlMessage::FileSendRequest(FileSendRequest {
                token: 7,
                root_name: "assets".to_owned(),
                total_bytes: 1024,
                clipboard: true,
            }),
            ControlMessage::FileSendGrant(FileSendGrant {
                token: 7,
                granted: true,
            }),
            ControlMessage::FileSendRelease(FileSendRelease { token: 7 }),
            ControlMessage::TransferCancel(TransferCancel {
                task_id: "send-1-2".to_owned(),
            }),
            ControlMessage::TransferPause(TransferPause {
                task_id: "send-1-2".to_owned(),
                paused: true,
            }),
            ControlMessage::PairSettings(PairSettings {
                edge: EdgeSide::Left,
                pointer_speed: 1.5,
                edge_resistance: 40,
                revision: 2,
            }),
            ControlMessage::FeatureSet(FeatureSet {
                clipboard: true,
                input: false,
                revision: 4,
            }),
            ControlMessage::Heartbeat(Heartbeat {
                seq: 5,
                ts_us: 123_456,
            }),
            ControlMessage::Error(ProtocolError::new(ErrorCode::DiskFull)),
        ]
    }

    #[test]
    fn every_c0_message_roundtrips_through_json() {
        for message in sample_messages() {
            let json = message.to_json().unwrap();
            let decoded = ControlMessage::from_json(&json).unwrap();
            assert_eq!(decoded, message);
        }
    }

    #[test]
    fn internally_tagged_shape_is_stable() {
        let json = ControlMessage::Heartbeat(Heartbeat { seq: 1, ts_us: 2 })
            .to_json()
            .unwrap();
        assert_eq!(json, r#"{"type":"heartbeat","seq":1,"ts_us":2}"#);
    }

    #[test]
    fn capabilities_are_serialised_as_a_bitmask() {
        let hello = sample_hello();
        let value = serde_json::to_value(hello.capabilities).unwrap();
        assert_eq!(
            value,
            serde_json::json!(
                Capabilities::INPUT.0
                    | Capabilities::CLIPBOARD_TEXT.0
                    | Capabilities::FILE_TRANSFER.0
            )
        );
        assert!(hello
            .capabilities
            .contains(Capabilities::INPUT | Capabilities::CLIPBOARD_TEXT));
        assert!(!hello
            .capabilities
            .contains(Capabilities::DIRECTORY_TRANSFER));
    }

    #[test]
    fn pair_settings_clamp_into_supported_range() {
        let normalized = PairSettings {
            edge: EdgeSide::Left,
            pointer_speed: f64::NAN,
            edge_resistance: u8::MAX,
            revision: 1,
        }
        .normalized();
        assert_eq!(normalized.pointer_speed, 1.0);
        assert_eq!(normalized.edge_resistance, MAX_EDGE_RESISTANCE);

        let clamped = PairSettings {
            edge: EdgeSide::Right,
            pointer_speed: 9.0,
            edge_resistance: 0,
            revision: 1,
        }
        .normalized();
        assert_eq!(clamped.pointer_speed, MAX_POINTER_SPEED);
        assert_eq!(clamped.edge, EdgeSide::Right);
    }

    #[test]
    fn control_error_defaults_are_actionable() {
        let error = ProtocolError::new(ErrorCode::PairRequired);
        assert_eq!(error.message, ErrorCode::PairRequired.message());
        assert!(!error.retryable);
    }
}
