/// Which local screen edge hands input to the peer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum EdgeSide {
    Left,
    #[default]
    Right,
}

/// Pair-level settings mirrored to the peer so both sides agree on how the
/// shared edge behaves.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PairSettings {
    pub edge: EdgeSide,
    /// Multiplier applied to physical pointer deltas; 1.0 keeps 1:1 mm.
    pub pointer_speed: f64,
    /// Milliseconds the pointer must stay on the edge before crossing.
    /// 0 crosses as soon as the edge is reached.
    pub edge_resistance: u8,
    pub revision: u64,
}

pub const MIN_POINTER_SPEED: f64 = 0.25;
pub const MAX_POINTER_SPEED: f64 = 3.0;
pub const MAX_EDGE_RESISTANCE: u8 = 200;

impl PairSettings {
    /// Replaces non-finite values and clamps fields into their supported range.
    pub fn normalized(mut self) -> Self {
        if !self.pointer_speed.is_finite() {
            self.pointer_speed = 1.0;
        }
        self.pointer_speed = self
            .pointer_speed
            .clamp(MIN_POINTER_SPEED, MAX_POINTER_SPEED);
        self.edge_resistance = self.edge_resistance.min(MAX_EDGE_RESISTANCE);
        self
    }
}

